'use client';

/**
 * أوامر الشراء — the commitment made to a supplier before any money moves.
 *
 * A purchase order is not a purchase invoice. It is the promise: this is what we asked for, at
 * this price, expected on this date. The invoice comes later and should match it — which is the
 * whole reason the order exists as its own document rather than as a note on the invoice.
 *
 * ── The lifecycle is the screen ───────────────────────────────────────────────────────────
 *
 *   مسودة → (بانتظار الاعتماد | مُرسل) → استلام جزئي → تم الاستلام → فاتورة مورد
 *
 * A draft carries no number. The number is assigned the moment it stops being a draft, because
 * a document number is a commitment and handing one out for something that may never be sent
 * leaves gaps in the sequence nobody can account for later.
 *
 * ── The threshold decides, not the person ────────────────────────────────────────────────
 *
 * Whether an order needs approval is settled by its base-currency total against a configured
 * threshold, applied by the server at creation. Nobody chooses "this one needs approving" —
 * which is the point: the rule cannot be routed around by whoever is raising the order.
 *
 * ── Receiving adds, it does not set ───────────────────────────────────────────────────────
 *
 * `receivedQuantity` on the receive call is what arrived in THIS delivery; the server adds it
 * to what was already received and caps it at the quantity ordered. So the form asks for the
 * delivery, not the running total — asking for the total and sending it as a delta is how a
 * second partial delivery silently doubles the stock on hand.
 */

import { useCallback, useEffect, useMemo, useState } from 'react';
import { api, ApiError } from '@/lib/api';
import { useI18n } from '@/lib/i18n';
import { useSession } from '@/lib/session';
import { PageHero, Panel, Skeleton } from '@/components/page';
import { selectableParties } from '@/lib/parties';

type Line = {
  id: string; itemId: string | null; itemName: string | null;
  description: string; quantity: number; unit: string;
  unitPrice: number; lineTotal: number; receivedQuantity: number;
};
type PO = {
  id: string; supplierId: string; supplierName: string | null; number: string | null;
  poDate: string; expectedDate: string | null; currencyCode: string;
  subTotal: number; taxTotal: number; totalAmount: number; totalBase: number;
  taxMode: 'TAX' | 'NORMAL'; status: string;
  approvedAt: string | null; isAutoGenerated: boolean; notes: string | null;
  linkedInvoiceCount: number | null; linkedInvoiceNumbers: string | null;
  lines?: Line[];
};
type Supplier = { id: string; name: string; isActive?: boolean };
type Item = { id: string; name: string; unit?: string | null };

const STATUSES = ['DRAFT', 'PENDING_APPROVAL', 'SENT', 'PARTIAL', 'RECEIVED', 'CANCELLED'] as const;
const STATUS_TONE: Record<string, string> = {
  DRAFT: 'ae-badge-muted', PENDING_APPROVAL: 'ae-badge-warn', SENT: 'ae-badge-info',
  PARTIAL: 'ae-badge-warn', RECEIVED: 'ae-badge-success', CANCELLED: 'ae-badge-danger',
};

type FormLine = { description: string; quantity: string; unit: string; unitPrice: string; itemId: string };
const BLANK_LINE: FormLine = { description: '', quantity: '1', unit: '', unitPrice: '', itemId: '' };

export default function PurchaseOrdersPage() {
  const { t, lang } = useI18n();
  const { can } = useSession();

  const manage = can('finance.purchases.manage');
  const settingsManage = can('settings.manage');

  const [orders, setOrders] = useState<PO[]>([]);
  const [suppliers, setSuppliers] = useState<Supplier[]>([]);
  const [items, setItems] = useState<Item[]>([]);
  const [threshold, setThreshold] = useState<number | null>(null);
  const [thresholdDraft, setThresholdDraft] = useState('');

  const [statusFilter, setStatusFilter] = useState('');
  const [supplierFilter, setSupplierFilter] = useState('');
  const [query, setQuery] = useState('');
  const [applied, setApplied] = useState('');

  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [flash, setFlash] = useState<string | null>(null);

  const [editing, setEditing] = useState(false);
  const [form, setForm] = useState({
    supplierId: '', poDate: new Date().toISOString().slice(0, 10), expectedDate: '',
    currencyCode: 'EGP', taxMode: 'TAX' as 'TAX' | 'NORMAL', notes: '',
  });
  const [formLines, setFormLines] = useState<FormLine[]>([{ ...BLANK_LINE }]);

  /** The order being looked at, with its lines — the list endpoint does not carry them. */
  const [open, setOpen] = useState<PO | null>(null);
  /** What arrived in this delivery, per line. Empty means nothing arrived for that line. */
  const [receiving, setReceiving] = useState<Record<string, string>>({});

  const money = useCallback(
    (v: number, currency = 'EGP') => new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-EG', {
      style: 'currency', currency, maximumFractionDigits: 2,
    }).format(v),
    [lang],
  );
  const num = useCallback(
    (v: number) => new Intl.NumberFormat(lang === 'ar' ? 'ar-EG' : 'en-EG', { maximumFractionDigits: 3 }).format(v),
    [lang],
  );
  const date = useCallback(
    (v: string | null) => (v ? new Date(v).toLocaleDateString(lang === 'ar' ? 'ar-EG' : 'en-GB') : '—'),
    [lang],
  );

  const load = useCallback(async () => {
    setLoading(true);
    try {
      const params = new URLSearchParams();
      if (statusFilter) params.set('status', statusFilter);
      if (supplierFilter) params.set('supplierId', supplierFilter);
      if (applied) params.set('q', applied);
      const [po, sp, it, st] = await Promise.all([
        api<PO[]>(`/purchase-orders${params.toString() ? `?${params}` : ''}`),
        api<Supplier[]>('/suppliers').catch(() => [] as Supplier[]),
        api<Item[]>('/inventory/items').catch(() => [] as Item[]),
        api<{ poApprovalThreshold?: number }>('/purchase-orders/settings')
          .catch(() => ({} as { poApprovalThreshold?: number })),
      ]);
      setOrders(Array.isArray(po) ? po : []);
      setSuppliers(Array.isArray(sp) ? sp : []);
      setItems(Array.isArray(it) ? it : []);
      if (st.poApprovalThreshold !== undefined) {
        setThreshold(st.poApprovalThreshold);
        setThresholdDraft(String(st.poApprovalThreshold));
      }
    } catch {
      setError('purchaseOrders.loadFailed');
    } finally {
      setLoading(false);
    }
  }, [statusFilter, supplierFilter, applied]);

  useEffect(() => {
    void load();
  }, [load]);

  async function call(path: string, method: 'POST' | 'PUT' | 'DELETE', body?: Record<string, unknown>, ok?: string) {
    setBusy(true);
    setError(null);
    setFlash(null);
    try {
      const res = await api<Record<string, unknown>>(path, { method, ...(body ? { body } : {}) });
      if (ok) setFlash(ok);
      await load();
      return res;
    } catch (err) {
      const code = err instanceof ApiError ? err.code : '';
      setError(code ? `purchaseOrders.error.${code}` : 'purchaseOrders.saveFailed');
      return null;
    } finally {
      setBusy(false);
    }
  }

  /** Lines total as the server will compute it, so the form can show what it is about to send. */
  const previewSubtotal = useMemo(
    () => formLines.reduce((sum, l) => sum + Number(l.quantity || 0) * Number(l.unitPrice || 0), 0),
    [formLines],
  );

  const setLine = (i: number, patch: Partial<FormLine>) =>
    setFormLines((ls) => ls.map((l, x) => (x === i ? { ...l, ...patch } : l)));

  async function save(status: 'DRAFT' | 'SENT') {
    const lines = formLines
      .filter((l) => l.description.trim() !== '')
      .map((l) => ({
        description: l.description.trim(),
        quantity: Number(l.quantity || 0),
        unit: l.unit.trim() || undefined,
        unitPrice: Number(l.unitPrice || 0),
        itemId: l.itemId || null,
      }));
    if (lines.length === 0) {
      setError('purchaseOrders.error.lines_required');
      return;
    }
    const res = await call('/purchase-orders', 'POST', {
      supplierId: form.supplierId,
      poDate: form.poDate,
      expectedDate: form.expectedDate || null,
      currencyCode: form.currencyCode,
      taxMode: form.taxMode,
      notes: form.notes.trim() || null,
      // The server decides between SENT and PENDING_APPROVAL from the threshold; asking for
      // anything but DRAFT simply means "this is not a draft any more".
      status,
      lines,
    }, 'purchaseOrders.created');
    if (res) {
      setEditing(false);
      setFormLines([{ ...BLANK_LINE }]);
      setForm({ ...form, notes: '', expectedDate: '' });
    }
  }

  async function openOrder(id: string) {
    setError(null);
    try {
      const po = await api<PO>(`/purchase-orders/${id}`);
      setOpen(po);
      setReceiving({});
    } catch {
      setError('purchaseOrders.loadFailed');
    }
  }

  async function receive() {
    if (!open) return;
    const lines = Object.entries(receiving)
      .map(([lineId, qty]) => ({ lineId, receivedQuantity: Number(qty || 0) }))
      .filter((l) => l.receivedQuantity > 0);
    if (lines.length === 0) {
      setError('purchaseOrders.receiveQtyRequired');
      return;
    }
    const res = await call(`/purchase-orders/${open.id}/receive`, 'POST', { lines }, 'purchaseOrders.received');
    if (res) await openOrder(open.id);
  }

  if (loading) {
    return (
      <div className="ae-page">
        <PageHero title={t('purchaseOrders.title')} subtitle={t('purchaseOrders.subtitle')} />
        <Panel><Skeleton rows={6} /></Panel>
      </div>
    );
  }

  return (
    <div className="ae-page">
      <PageHero title={t('purchaseOrders.title')} subtitle={t('purchaseOrders.subtitle')}
        actions={manage && (
          <span className="flex flex-wrap gap-2">
            <button type="button" className="ae-btn-primary" onClick={() => { setEditing(true); setOpen(null); }}>
              {t('purchaseOrders.new')}
            </button>
            {/* Inventory knows what has fallen below its reorder level and who normally
                supplies it; this turns that into draft orders in one go. */}
            {can('inventory.manage') && (
              <button type="button" className="ae-btn-secondary" disabled={busy}
                onClick={async () => {
                  const res = await call('/purchase-orders/generate-reorders', 'POST', {}, undefined);
                  if (!res) return;
                  // Field names read off a real response, not guessed: the endpoint returns the
                  // orders it made, a count of suppliers it skipped, and the items it could not
                  // order because nothing says who supplies them.
                  const created = (res.createdOrders as unknown[] | undefined)?.length ?? 0;
                  const skipped = Number(res.skippedSupplierCount ?? 0);
                  const orphans = res.itemsWithoutSupplier as string[] | undefined;
                  setFlash([
                    t('purchaseOrders.reordersCreated', { n: String(created) }),
                    skipped ? t('purchaseOrders.reordersSkipped', { n: String(skipped) }) : '',
                    orphans?.length ? t('purchaseOrders.itemsWithoutSupplier', { items: orphans.join('، ') }) : '',
                  ].filter(Boolean).join(' · '));
                }}>
                {t('purchaseOrders.generateReorders')}
              </button>
            )}
          </span>
        )} />

      {error && <p className="ae-flash ae-flash--error mb-4">{t(error, t('common.error'))}</p>}
      {flash && <p className="ae-flash ae-flash--success mb-4">{t(flash, flash)}</p>}

      {settingsManage && threshold !== null && (
        <Panel className="mb-4">
          <div className="grid gap-3 sm:grid-cols-[1fr_auto] sm:items-end">
            <label className="text-sm">
              <span className="mb-1 block font-bold">{t('purchaseOrders.threshold')}</span>
              <input type="number" min="0" step="any" className="ae-input" value={thresholdDraft}
                onChange={(e) => setThresholdDraft(e.target.value)} />
              <span className="mt-1 block text-xs text-[var(--text-muted)]">{t('purchaseOrders.thresholdHint')}</span>
            </label>
            <button type="button" className="ae-btn-secondary text-xs" disabled={busy}
              onClick={() => void call('/purchase-orders/settings', 'PUT',
                { poApprovalThreshold: Number(thresholdDraft || 0) }, 'common.success')}>
              {t('common.save')}
            </button>
          </div>
        </Panel>
      )}

      <Panel>
        <form className="ae-toolbar mb-3"
          onSubmit={(e) => { e.preventDefault(); setApplied(query.trim()); }}>
          <label className="text-sm">
            <span className="mb-1 block font-bold">{t('purchaseOrders.search')}</span>
            <input className="ae-input" value={query} onChange={(e) => setQuery(e.target.value)} />
          </label>
          <label className="text-sm">
            <span className="mb-1 block font-bold">{t('purchaseOrders.status')}</span>
            <select className="ae-input" value={statusFilter} onChange={(e) => setStatusFilter(e.target.value)}>
              <option value="">{t('purchaseOrders.allStatuses')}</option>
              {STATUSES.map((s) => <option key={s} value={s}>{t(`purchaseOrders.status.${s}`)}</option>)}
            </select>
          </label>
          <label className="text-sm">
            <span className="mb-1 block font-bold">{t('purchaseOrders.supplier')}</span>
            <select className="ae-input" value={supplierFilter} onChange={(e) => setSupplierFilter(e.target.value)}>
              <option value="">{t('common.all')}</option>
              {selectableParties(suppliers, supplierFilter).map((s) => (
                <option key={s.id} value={s.id}>{s.name}</option>
              ))}
            </select>
          </label>
          <button type="submit" className="ae-btn-primary self-end">{t('purchaseOrders.search')}</button>
        </form>

        {orders.length === 0 ? (
          <p className="text-sm text-[var(--text-muted)]">{t('purchaseOrders.noRecords')}</p>
        ) : (
          <div className="ae-table-wrap">
            <table className="ae-table">
              <thead>
                <tr>
                  <th>{t('purchaseOrders.number')}</th>
                  <th>{t('purchaseOrders.supplier')}</th>
                  <th>{t('purchaseOrders.poDate')}</th>
                  <th>{t('purchaseOrders.expectedDate')}</th>
                  <th>{t('purchases.total')}</th>
                  <th>{t('purchaseOrders.status')}</th>
                  <th>{t('purchaseOrders.linkedInvoices')}</th>
                  <th aria-label={t('quotes.actions')} />
                </tr>
              </thead>
              <tbody>
                {orders.map((po) => (
                  <tr key={po.id}>
                    <td>
                      {/* A draft has no number yet — saying so beats an empty cell. */}
                      {po.number ?? <span className="text-xs text-[var(--text-muted)]">{t('purchaseOrders.status.DRAFT')}</span>}
                      {po.isAutoGenerated && (
                        <span className="block text-xs text-[var(--text-muted)]">{t('purchaseOrders.autoGenerated')}</span>
                      )}
                    </td>
                    <td>{po.supplierName ?? '—'}</td>
                    <td className="text-xs">{date(po.poDate)}</td>
                    <td className="text-xs">{date(po.expectedDate)}</td>
                    <td className="font-bold">{money(po.totalAmount, po.currencyCode)}</td>
                    <td>
                      <span className={`ae-badge ${STATUS_TONE[po.status] ?? 'ae-badge-muted'} text-xs`}>
                        {t(`purchaseOrders.status.${po.status}`, po.status)}
                      </span>
                    </td>
                    <td className="text-xs">{po.linkedInvoiceNumbers || (po.linkedInvoiceCount ? num(po.linkedInvoiceCount) : '—')}</td>
                    <td>
                      <span className="flex flex-wrap gap-1">
                        <button type="button" className="ae-btn-ghost px-2 py-1 text-xs"
                          onClick={() => { void openOrder(po.id); setEditing(false); }}>
                          {t('purchaseOrders.view')}
                        </button>
                        {manage && po.status === 'PENDING_APPROVAL' && (
                          <button type="button" className="ae-btn-ghost px-2 py-1 text-xs" disabled={busy}
                            onClick={() => void call(`/purchase-orders/${po.id}/approve`, 'POST', {}, 'purchaseOrders.approved')}>
                            {t('purchaseOrders.approve')}
                          </button>
                        )}
                        {/* Offered once. The conversion bills the whole received quantity, so a
                            second one re-bills what was already invoiced; the API refuses it and
                            the button goes away rather than inviting the attempt. */}
                        {manage && ['SENT', 'PARTIAL', 'RECEIVED'].includes(po.status)
                          && !(po.linkedInvoiceCount ?? 0) && (
                          <button type="button" className="ae-btn-ghost px-2 py-1 text-xs" disabled={busy}
                            onClick={() => void call(`/purchase-orders/${po.id}/convert-to-invoice`, 'POST', {}, 'purchaseOrders.converted')}>
                            {t('purchaseOrders.convertToInvoice')}
                          </button>
                        )}
                        {manage && !['PARTIAL', 'RECEIVED', 'CANCELLED'].includes(po.status) && (
                          <button type="button" className="ae-btn-ghost px-2 py-1 text-xs" disabled={busy}
                            onClick={() => {
                              if (!window.confirm(t('purchaseOrders.confirmCancel'))) return;
                              void call(`/purchase-orders/${po.id}`, 'DELETE', undefined, 'purchaseOrders.cancelled');
                            }}>
                            {t('purchaseOrders.cancel')}
                          </button>
                        )}
                      </span>
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </Panel>

      {open && (
        <Panel title={open.number ?? t('purchaseOrders.status.DRAFT')} className="mt-4"
          actions={<button type="button" className="ae-btn-ghost text-xs" onClick={() => setOpen(null)}>
            {t('common.cancel')}
          </button>}>
          <div className="mb-3 grid gap-1 text-sm">
            <span>{t('purchaseOrders.supplier')}: <strong>{open.supplierName}</strong></span>
            <span>{t('purchaseOrders.expectedDate')}: {date(open.expectedDate)}</span>
            {open.notes && <span className="text-xs text-[var(--text-muted)]">{open.notes}</span>}
          </div>

          <div className="ae-table-wrap">
            <table className="ae-table">
              <thead>
                <tr>
                  <th>{t('invoices.description')}</th>
                  <th>{t('invoices.quantity')}</th>
                  <th>{t('purchaseOrders.receivedQuantity')}</th>
                  <th>{t('pricing.unitPrice')}</th>
                  <th>{t('invoices.lineTotal')}</th>
                  {manage && ['SENT', 'PARTIAL'].includes(open.status) && (
                    <th>{t('purchaseOrders.receiveNow')}</th>
                  )}
                </tr>
              </thead>
              <tbody>
                {(open.lines ?? []).map((l) => {
                  const outstanding = l.quantity - l.receivedQuantity;
                  return (
                    <tr key={l.id}>
                      <td>{l.description}{l.itemName && <span className="block text-xs text-[var(--text-muted)]">{l.itemName}</span>}</td>
                      <td>{num(l.quantity)} {l.unit}</td>
                      <td>{num(l.receivedQuantity)}</td>
                      <td>{money(l.unitPrice, open.currencyCode)}</td>
                      <td>{money(l.lineTotal, open.currencyCode)}</td>
                      {manage && ['SENT', 'PARTIAL'].includes(open.status) && (
                        <td>
                          {/* Capped at what is still outstanding, matching the server, so the
                              field cannot ask for more than the order has left to deliver. */}
                          <input type="number" min="0" max={outstanding} step="any" className="ae-input w-24"
                            value={receiving[l.id] ?? ''} disabled={outstanding <= 0}
                            onChange={(e) => setReceiving({ ...receiving, [l.id]: e.target.value })} />
                        </td>
                      )}
                    </tr>
                  );
                })}
              </tbody>
              <tfoot>
                <tr>
                  <th colSpan={3}>{t('invoices.subTotal')}</th>
                  <th colSpan={2}>{money(open.subTotal, open.currencyCode)}</th>
                </tr>
                <tr>
                  <th colSpan={3}>{t('invoices.tax')}</th>
                  <th colSpan={2}>{money(open.taxTotal, open.currencyCode)}</th>
                </tr>
                <tr>
                  <th colSpan={3}>{t('purchases.total')}</th>
                  <th colSpan={2}>{money(open.totalAmount, open.currencyCode)}</th>
                </tr>
              </tfoot>
            </table>
          </div>

          {manage && ['SENT', 'PARTIAL'].includes(open.status) && (
            <button type="button" className="ae-btn-primary mt-3" disabled={busy} onClick={() => void receive()}>
              {t('purchaseOrders.recordReceiving')}
            </button>
          )}
        </Panel>
      )}

      {editing && (
        <Panel title={t('purchaseOrders.new')} className="mt-4">
          <div className="grid gap-3 sm:grid-cols-2 lg:grid-cols-4">
            <label className="text-sm">
              <span className="mb-1 block font-bold">{t('purchaseOrders.supplier')}</span>
              <select className="ae-input" value={form.supplierId}
                onChange={(e) => setForm({ ...form, supplierId: e.target.value })}>
                <option value="">—</option>
                {selectableParties(suppliers, form.supplierId).map((s) => (
                  <option key={s.id} value={s.id}>{s.name}</option>
                ))}
              </select>
            </label>
            <label className="text-sm">
              <span className="mb-1 block font-bold">{t('purchaseOrders.poDate')}</span>
              <input type="date" className="ae-input" value={form.poDate}
                onChange={(e) => setForm({ ...form, poDate: e.target.value })} />
            </label>
            <label className="text-sm">
              <span className="mb-1 block font-bold">{t('purchaseOrders.expectedDate')}</span>
              <input type="date" className="ae-input" value={form.expectedDate}
                onChange={(e) => setForm({ ...form, expectedDate: e.target.value })} />
            </label>
            <label className="text-sm">
              <span className="mb-1 block font-bold">{t('purchases.taxMode')}</span>
              <select className="ae-input" value={form.taxMode}
                onChange={(e) => setForm({ ...form, taxMode: e.target.value as 'TAX' | 'NORMAL' })}>
                {(['TAX', 'NORMAL'] as const).map((m) => (
                  <option key={m} value={m}>{t(`purchases.taxMode.${m}`)}</option>
                ))}
              </select>
            </label>
          </div>

          <h4 className="mb-2 mt-4 text-sm font-bold">{t('purchases.lines')}</h4>
          <div className="grid gap-2">
            {formLines.map((l, i) => (
              <div key={i} className="grid items-end gap-2 sm:grid-cols-[2fr_1fr_1fr_1fr_auto]">
                <label className="text-sm">
                  <span className="mb-1 block text-xs font-bold">{t('invoices.description')}</span>
                  <input className="ae-input" value={l.description} list={`po-items-${i}`}
                    onChange={(e) => {
                      // Typing a catalogue item's name links the line to it, which is what
                      // makes receiving move real stock rather than just a number on paper.
                      const match = items.find((x) => x.name === e.target.value);
                      setLine(i, {
                        description: e.target.value,
                        itemId: match?.id ?? '',
                        ...(match?.unit ? { unit: match.unit } : {}),
                      });
                    }} />
                  <datalist id={`po-items-${i}`}>
                    {items.map((x) => <option key={x.id} value={x.name} />)}
                  </datalist>
                </label>
                <label className="text-sm">
                  <span className="mb-1 block text-xs font-bold">{t('invoices.quantity')}</span>
                  <input type="number" min="0" step="any" className="ae-input" value={l.quantity}
                    onChange={(e) => setLine(i, { quantity: e.target.value })} />
                </label>
                <label className="text-sm">
                  <span className="mb-1 block text-xs font-bold">{t('inventory.unit')}</span>
                  <input className="ae-input" value={l.unit}
                    onChange={(e) => setLine(i, { unit: e.target.value })} />
                </label>
                <label className="text-sm">
                  <span className="mb-1 block text-xs font-bold">{t('pricing.unitPrice')}</span>
                  <input type="number" min="0" step="any" className="ae-input" value={l.unitPrice}
                    onChange={(e) => setLine(i, { unitPrice: e.target.value })} />
                </label>
                <button type="button" className="ae-btn-ghost px-3 py-1 text-xs" disabled={formLines.length <= 1}
                  onClick={() => setFormLines(formLines.filter((_, x) => x !== i))}>
                  {t('invoices.removeLine')}
                </button>
              </div>
            ))}
          </div>

          <label className="mt-3 block text-sm">
            <span className="mb-1 block font-bold">{t('invoices.notes')}</span>
            <textarea className="ae-input" rows={2} value={form.notes}
              onChange={(e) => setForm({ ...form, notes: e.target.value })} />
          </label>

          <p className="mt-3 text-sm">
            {t('purchaseOrders.previewTotal')}: <strong>{money(previewSubtotal, form.currencyCode)}</strong>
            {/* Tax is the server's to add, so the preview says what it is: before tax. */}
            <span className="ms-2 text-xs text-[var(--text-muted)]">{t('invoices.subTotal')}</span>
          </p>
          {threshold !== null && previewSubtotal > threshold && (
            <p className="ae-alert-pill ae-alert-pill--warn mt-2 block text-xs">
              {t('purchaseOrders.willNeedApproval', { threshold: money(threshold) })}
            </p>
          )}

          <div className="mt-3 flex flex-wrap gap-2">
            <button type="button" className="ae-btn-ghost" disabled={busy || form.supplierId === ''}
              onClick={() => void save('DRAFT')}>
              {t('purchaseOrders.saveDraft')}
            </button>
            <button type="button" className="ae-btn-primary" disabled={busy || form.supplierId === ''}
              onClick={() => void save('SENT')}>
              {t('purchaseOrders.sendToSupplier')}
            </button>
            <button type="button" className="ae-btn-ghost" onClick={() => setEditing(false)}>
              {t('common.cancel')}
            </button>
          </div>
        </Panel>
      )}
    </div>
  );
}
